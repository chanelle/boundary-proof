"""Regenerate the demo's engine data from the real BoundaryProof engine.

Usage (from repo root):
    python3 demo/build_demo_data.py

Runs boundaryproof.engine on fixtures/f09_permission_nobody_gave.json with
policies/auto.json and writes:
    demo/data/engine_output.json   raw assessment JSON (engine.to_dict())
    demo/js/engine-data.js         same payload wrapped for file:// use

Nothing in these files is hand-edited. tests/test_demo_data.py fails if they
drift from a fresh engine run.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from boundaryproof import engine  # noqa: E402

FIXTURE = os.path.join(ROOT, "fixtures", "f09_permission_nobody_gave.json")
POLICY = os.path.join(ROOT, "policies", "auto.json")
OUT_JSON = os.path.join(ROOT, "demo", "data", "engine_output.json")
OUT_JS = os.path.join(ROOT, "demo", "js", "engine-data.js")


def build() -> dict:
    assessment = engine.run_file(FIXTURE, policy_path=POLICY)
    with open(FIXTURE, "rb") as fh:
        fixture_sha = hashlib.sha256(fh.read()).hexdigest()
    return {
        "_provenance": {
            "generator": "demo/build_demo_data.py",
            "engine": "boundaryproof (this repository)",
            "fixture": "fixtures/f09_permission_nobody_gave.json",
            "fixture_sha256": fixture_sha,
            "policy": "policies/auto.json",
            "note": "Generated by running the real engine. Do not hand-edit.",
        },
        "assessment": assessment.to_dict(),
    }


def main() -> int:
    payload = build()
    text = json.dumps(payload, indent=2, sort_keys=True)
    with open(OUT_JSON, "w") as fh:
        fh.write(text + "\n")
    with open(OUT_JS, "w") as fh:
        fh.write("// GENERATED by demo/build_demo_data.py from the real BoundaryProof engine.\n")
        fh.write("// Do not hand-edit. Regenerate with: python3 demo/build_demo_data.py\n")
        fh.write("window.MIMO_ENGINE = " + text + ";\n")
    print(f"wrote {os.path.relpath(OUT_JSON, ROOT)} and {os.path.relpath(OUT_JS, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
